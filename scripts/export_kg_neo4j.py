"""Export the typed knowledge graph for Neo4j.

    python -m scripts.export_kg_neo4j            # writes data/processed/kg/

Writes nodes.csv, edges.csv and import.cypher. Copy the two CSVs into Neo4j's
import folder and run import.cypher in the Neo4j Browser (or cypher-shell) to
get the same graph the recommender scores in memory: Item, Person, Brand, Genre,
Franchise, Keyword, ContentType and Domain nodes joined by typed relationships.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from backend.kg_graph import RELATION_NAMES, TypedKnowledgeGraph

PROJECT_ROOT = Path(__file__).resolve().parents[1]

CYPHER = """// Generated by scripts/export_kg_neo4j.py - run after copying nodes.csv and edges.csv into Neo4j's import folder.
CREATE CONSTRAINT node_id IF NOT EXISTS FOR (n:Node) REQUIRE n.id IS UNIQUE;

LOAD CSV WITH HEADERS FROM 'file:///nodes.csv' AS row
CALL {{ WITH row
  CALL apoc.create.node(['Node', row.label], {{id: row.id, name: row.name}}) YIELD node
  RETURN count(*) AS created
}} IN TRANSACTIONS OF 10000 ROWS
RETURN count(*);

// Without APOC: one MERGE per label, e.g.
// LOAD CSV WITH HEADERS FROM 'file:///nodes.csv' AS row WITH row WHERE row.label = 'Person'
// MERGE (n:Node:Person {{id: row.id}}) SET n.name = row.name;

{edges}
"""

EDGE_BLOCK = """LOAD CSV WITH HEADERS FROM 'file:///edges.csv' AS row WITH row WHERE row.type = '{rel}'
CALL {{ WITH row
  MATCH (a:Node {{id: row.source}}), (b:Node {{id: row.target}})
  MERGE (a)-[:{rel}]->(b)
}} IN TRANSACTIONS OF 10000 ROWS;
"""


def main() -> None:
    parser = argparse.ArgumentParser(description="Export the knowledge graph as Neo4j import files.")
    parser.add_argument("--catalog", type=Path, default=PROJECT_ROOT / "data" / "processed" / "content_catalog.csv")
    parser.add_argument("--out", type=Path, default=PROJECT_ROOT / "data" / "processed" / "kg")
    args = parser.parse_args()

    catalog = pd.read_csv(args.catalog, low_memory=False)
    graph = TypedKnowledgeGraph.from_catalog(catalog)
    nodes, edges = graph.export_rows()

    args.out.mkdir(parents=True, exist_ok=True)
    nodes.to_csv(args.out / "nodes.csv", index=False)
    edges.to_csv(args.out / "edges.csv", index=False)
    blocks = "\n".join(EDGE_BLOCK.format(rel=rel) for rel in RELATION_NAMES)
    (args.out / "import.cypher").write_text(CYPHER.format(edges=blocks), encoding="utf-8")
    (args.out / "stats.json").write_text(json.dumps(graph.stats(), indent=2), encoding="utf-8")

    print(json.dumps(graph.stats(), indent=2))
    print(f"wrote {len(nodes):,} nodes and {len(edges):,} edges to {args.out}")


if __name__ == "__main__":
    main()
